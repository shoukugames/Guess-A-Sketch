def _snowflake():
    out = []
    for a in range(-90, 270, 60):
        ra = math.radians(a)
        out.append(L(50, 50, 50 + 40 * math.cos(ra), 50 + 40 * math.sin(ra), col=BLUE))
    for a in range(-90, 270, 60):
        for r, ln in ((22, 10), (32, 6)):
            ra = math.radians(a)
            bx, by = 50 + r * math.cos(ra), 50 + r * math.sin(ra)
            for off in (-45, 45):
                rb = math.radians(a + off)
                out.append(L(bx, by, bx + ln * math.cos(rb), by + ln * math.sin(rb), col=BLUE))
    out.append(P([(50 + 8 * math.cos(math.radians(a)), 50 + 8 * math.sin(math.radians(a))) for a in range(-90, 270, 60)], LTBLUE))
    return out


