# ---------------------------------------------------------------- helpers
def prim(pts, closed=False, fill=None, z=0, col=None):
    return {"pts": [(float(x), float(y)) for x, y in pts], "closed": closed,
            "fill": fill, "z": z, "col": col}


def _arc_pts(cx, cy, rx, ry, a0, a1, n=None):
    if n is None:
        n = max(8, int(abs(a1 - a0) / 360.0 * 60))
    out = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        out.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return out


def _catmull(pts, closed=False, steps=10):
    if len(pts) < 3:
        return list(pts)
    p = list(pts)
    if closed:
        ext = [p[-1]] + p + [p[0], p[1]]
        segs = len(p)
    else:
        ext = [p[0]] + p + [p[-1]]
        segs = len(p) - 1
    out = []
    for i in range(segs):
        p0, p1, p2, p3 = ext[i], ext[i + 1], ext[i + 2], ext[i + 3]
        for s in range(steps):
            t = s / steps
            t2, t3 = t * t, t * t * t
            x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t +
                       (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 +
                       (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
            y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t +
                       (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 +
                       (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
            out.append((x, y))
    if not closed:
        out.append(p[-1])
    return out


def _rot(pts, cx, cy, ang):
    a = math.radians(ang)
    ca, sa = math.cos(a), math.sin(a)
    return [(cx + (x - cx) * ca - (y - cy) * sa, cy + (x - cx) * sa + (y - cy) * ca) for x, y in pts]


def L(x1, y1, x2, y2, **kw):
    """Straight line."""
    return prim([(x1, y1), (x2, y2)], **kw)


def PL(pts, **kw):
    """Open polyline."""
    return prim(pts, **kw)


def P(pts, fill=None, **kw):
    """Closed polygon."""
    return prim(pts, closed=True, fill=fill, **kw)


def R(x, y, w, h, fill=None, **kw):
    return P([(x, y), (x + w, y), (x + w, y + h), (x, y + h)], fill, **kw)


def E(cx, cy, rx, ry, fill=None, **kw):
    return prim(_arc_pts(cx, cy, rx, ry, 0, 360)[:-1], closed=True, fill=fill, **kw)


def C(cx, cy, r, fill=None, **kw):
    return E(cx, cy, r, r, fill, **kw)


def A(cx, cy, rx, ry, a0, a1, **kw):
    """Open arc. Angles in degrees, 0 = right, 90 = down."""
    return prim(_arc_pts(cx, cy, rx, ry, a0, a1), **kw)


def HALF(cx, cy, rx, ry, a0, a1, fill=None, extra=None, **kw):
    """Closed arc segment (closed with a chord, or with extra points)."""
    pts = _arc_pts(cx, cy, rx, ry, a0, a1)
    if extra:
        pts += extra
    return prim(pts, closed=True, fill=fill, **kw)


def S(pts, **kw):
    """Smooth open curve through points."""
    return prim(_catmull(pts), **kw)


def SC(pts, fill=None, **kw):
    """Smooth closed curve through points."""
    return prim(_catmull(pts, closed=True), closed=True, fill=fill, **kw)


def tube(pts, w, fill=None, smooth=True, **kw):
    """Thick band of width w following a centre line."""
    c = _catmull(pts) if (smooth and len(pts) > 2) else list(pts)
    left, right = [], []
    n = len(c)
    for i in range(n):
        a = c[max(i - 1, 0)]
        b = c[min(i + 1, n - 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        d = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / d * w / 2, dx / d * w / 2
        left.append((c[i][0] + nx, c[i][1] + ny))
        right.append((c[i][0] - nx, c[i][1] - ny))
    return prim(left + right[::-1], closed=True, fill=fill, **kw)


def ROTR(cx, cy, w, h, ang, fill=None, **kw):
    pts = [(cx - w / 2, cy - h / 2), (cx + w / 2, cy - h / 2), (cx + w / 2, cy + h / 2), (cx - w / 2, cy + h / 2)]
    return P(_rot(pts, cx, cy, ang), fill, **kw)


def ROTE(cx, cy, rx, ry, ang, fill=None, **kw):
    pts = _arc_pts(cx, cy, rx, ry, 0, 360)[:-1]
    return prim(_rot(pts, cx, cy, ang), closed=True, fill=fill, **kw)


def STAR(cx, cy, ro, ri, fill=None, n=5, rot=-90, **kw):
    pts = []
    for i in range(n * 2):
        r = ro if i % 2 == 0 else ri
        a = math.radians(rot + i * 180.0 / n)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return P(pts, fill, **kw)


def HEART(cx, cy, s, fill=None, **kw):
    pts = []
    for i in range(60):
        t = 2 * math.pi * i / 60
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        pts.append((cx + x * s, cy - y * s))
    return P(pts, fill, **kw)


def DROP(x, y, s=1.0, fill=LTBLUE, **kw):
    return SC([(x, y - 6 * s), (x + 3.5 * s, y + 1 * s), (x, y + 4.5 * s), (x - 3.5 * s, y + 1 * s)], fill, **kw)


def SPIRAL(cx, cy, r0, turns, **kw):
    n = int(turns * 40)
    pts = []
    for i in range(n + 1):
        t = i / n
        a = 2 * math.pi * turns * t
        r = r0 * (1 - t)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return prim(pts, **kw)


def BAND(cx, cy, r1, r2, a0, a1, fill=None, **kw):
    outer = _arc_pts(cx, cy, r2, r2, a0, a1)
    inner = _arc_pts(cx, cy, r1, r1, a1, a0)
    return P(outer + inner, fill, **kw)


def MX(p):
    """Mirror a primitive left/right."""
    q = dict(p)
    q["pts"] = [(100 - x, y) for x, y in p["pts"]]
    return q


def pair(p):
    return [p, MX(p)]


def chord(cx, cy, rx, ry, k, slope):
    """Line y - cy = slope*(x - cx) + k clipped to an ellipse."""
    # Solve ((x)^2/rx^2) + ((slope*x + k)^2/ry^2) = 1 with x relative to cx.
    a = 1 / rx ** 2 + slope ** 2 / ry ** 2
    b = 2 * slope * k / ry ** 2
    c = k ** 2 / ry ** 2 - 1
    disc = b * b - 4 * a * c
    if disc <= 0:
        return None
    s = math.sqrt(disc)
    x1, x2 = (-b - s) / (2 * a), (-b + s) / (2 * a)
    return L(cx + x1, cy + slope * x1 + k, cx + x2, cy + slope * x2 + k)


def waves(y, amp=3, x0=5, x1=95, n=9, **kw):
    pts = []
    for i in range(n + 1):
        x = x0 + (x1 - x0) * i / n
        pts.append((x, y + (amp if i % 2 else -amp)))
    return S(pts, **kw)


# ---------------------------------------------------------------- word table
WORDS = {}   # word -> {"tier": int, "prims": [...]}


def add(word, tier, *prims):
    plist = [p for p in prims if p is not None]
    if len(plist) < STAGES:
        raise ValueError("%s needs at least %d primitives" % (word, STAGES))
    WORDS[word] = {"tier": tier, "prims": plist}


