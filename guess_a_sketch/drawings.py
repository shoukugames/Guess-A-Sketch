"""Vector sketches for every word in the game.

Every drawing lives in a 0..100 x 0..100 box (y grows downward) and is an
ordered list of primitives. The order is the order they are sketched in; the
list is split into 6 stages:

    stage 0  -> shown as the opening hint
    stage 1-5 -> revealed one per wrong guess (5 chances)

Each primitive is a dict:
    pts     list of (x, y) points (already tessellated)
    closed  whether the outline closes on itself
    fill    RGB fill used in the colored "finished" picture (None = outline only)
    z       draw order for occlusion (lower = further back)
    col     optional outline colour for the colored picture
"""

